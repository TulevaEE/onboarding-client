#!/usr/bin/env bash

E2E_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
E2E_CLIENT_DIR="${E2E_CLIENT_DIR:-$(cd "$E2E_DIR/.." && pwd)}"
E2E_BACKEND_DIR="${E2E_BACKEND_DIR:-}"
if [[ -n "${CI:-}" ]]; then
  E2E_BACKEND_BUILD="${E2E_BACKEND_BUILD:-always}"
else
  E2E_BACKEND_BUILD="${E2E_BACKEND_BUILD:-when-missing}"
fi
E2E_STATE_DIR="${E2E_STATE_DIR:-$E2E_DIR/.stack}"

E2E_BACKEND_PORT="${E2E_BACKEND_PORT:-9000}"
E2E_CLIENT_PORT="${E2E_CLIENT_PORT:-3200}"
E2E_CLIENT_HTTPS="${E2E_CLIENT_HTTPS:-false}"
if [[ "$E2E_CLIENT_HTTPS" == true ]]; then
  E2E_BASE_URL="${E2E_BASE_URL:-https://localhost:$E2E_CLIENT_PORT}"
else
  E2E_BASE_URL="${E2E_BASE_URL:-http://localhost:$E2E_CLIENT_PORT}"
fi
E2E_SMART_ID_CALLBACK_ORIGIN="${E2E_SMART_ID_CALLBACK_ORIGIN:-https://localhost:$E2E_CLIENT_PORT}"
E2E_BACKEND_URL="http://localhost:$E2E_BACKEND_PORT"

E2E_DATABASE_HOST="${E2E_DATABASE_HOST:-localhost}"
E2E_DATABASE_PORT="${E2E_DATABASE_PORT:-5432}"
E2E_DATABASE_NAME="${E2E_DATABASE_NAME:-tuleva_onboarding_e2e}"
E2E_DATABASE_USERNAME="${E2E_DATABASE_USERNAME:-tuleva-onboarding}"
E2E_DATABASE_PASSWORD="${E2E_DATABASE_PASSWORD:-tuleva-onboarding}"
E2E_CREATE_DATABASE="${E2E_CREATE_DATABASE:-true}"

E2E_STARTUP_TIMEOUT_SECONDS="${E2E_STARTUP_TIMEOUT_SECONDS:-300}"

export E2E_DIR E2E_CLIENT_DIR E2E_BACKEND_DIR E2E_BACKEND_BUILD E2E_STATE_DIR \
  E2E_BACKEND_PORT E2E_CLIENT_PORT E2E_CLIENT_HTTPS E2E_BASE_URL E2E_SMART_ID_CALLBACK_ORIGIN \
  E2E_BACKEND_URL E2E_DATABASE_HOST E2E_DATABASE_PORT E2E_DATABASE_NAME E2E_DATABASE_USERNAME \
  E2E_DATABASE_PASSWORD E2E_CREATE_DATABASE E2E_STARTUP_TIMEOUT_SECONDS
